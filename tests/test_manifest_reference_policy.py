"""Release-tree references must pass the manifest builder's own classifier."""
from pathlib import Path
import unittest

from scripts import skill_integrity


ROOT = Path(__file__).resolve().parents[1]


def reference_failures(skill, data, relative_path, rules):
    references, _, _, _ = skill_integrity._scan_text(data, relative_path)
    failures = []
    for reference in references:
        url = reference['url']
        rule = rules.get(url)
        if rule is None:
            failures.append(f"{skill}/{relative_path}:{reference['line']}: unclassified {url}")
        elif skill not in rule['allowedSkills']:
            failures.append(f"{skill}/{relative_path}:{reference['line']}: not allowed for skill {url}")
    return failures


class ManifestReferencePolicyTests(unittest.TestCase):
    def test_all_tracked_skill_references_are_classified(self):
        _, registered = skill_integrity._load_registry(ROOT / 'skills')
        policy = skill_integrity._load_json(ROOT / 'integrity/policy.json', 'integrity policy')
        skill_integrity._validate_policy(policy, registered)
        rules = skill_integrity._policy_reference_map(policy)
        failures = []
        scanned = 0
        # The release tree is tracked input; bare discovery's generated bytecode
        # is intentionally outside this reference-only regression's inventory.
        for name in skill_integrity._tracked_repository_paths(ROOT):
            parts = Path(name).parts
            if len(parts) < 3 or parts[0] != 'skills' or parts[1] not in registered:
                continue
            failures.extend(reference_failures(
                parts[1], (ROOT / name).read_bytes(), '/'.join(parts[2:]), rules,
            ))
            scanned += 1
        self.assertGreaterEqual(scanned, len(registered), 'empty tracked inventory cannot pass')
        self.assertEqual(failures, [], '\n'.join(failures))

    def test_classifier_rejects_unknown_remote_and_loopback_literals(self):
        source = b"git clone https://unknown.invalid/repo\nconst sink = `http://127.0.0.1:${port}/attempt`;\n"
        failures = reference_failures('fixture', source, 'test.txt', {})
        self.assertEqual(len(failures), 2)
        self.assertIn('unknown.invalid', failures[0])
        self.assertIn('127.0.0.1', failures[1])

    def test_classified_reference_still_requires_the_correct_skill(self):
        url = 'https://classified.invalid/reference'
        rules = {url: {'allowedSkills': ['allowed']}}
        self.assertEqual(reference_failures('allowed', url.encode(), 'test.txt', rules), [])
        failures = reference_failures('different', url.encode(), 'test.txt', rules)
        self.assertEqual(len(failures), 1)
        self.assertIn('not allowed for skill', failures[0])


if __name__ == '__main__':
    unittest.main()
